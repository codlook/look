static fs::path look_home() {
#ifdef _WIN32
    const char* home = std::getenv("USERPROFILE");
    if (!home) home = std::getenv("HOMEDRIVE");
#else
    const char* home = std::getenv("HOME");
#endif
    if (!home) throw std::runtime_error("HOME directory not found");
    return fs::path(home) / ".look";
}

static fs::path modules_dir() {
    return look_home() / "modules";
}

// ── cmd_module_install ────────────────────────────────────────────────────────

int cmd_module_install(const std::string& pkg_url, bool verbose) {
    PkgSpec spec;
    try {
        spec = parse_pkg(pkg_url);
    } catch (const std::exception& e) {
        std::cerr << "Error: " << e.what() << "\n";
        std::cerr << "Example: lk module install github.com/codlook/look-modules/jwt\n";
        return 1;
    }

    // Module name = subdir if given, otherwise repo name
    std::string mod_name = spec.subdir.empty() ? spec.repo : spec.subdir;

    std::cout << "Loading module: " << spec.user << "/" << spec.repo;
    if (!spec.subdir.empty()) std::cout << "/" << spec.subdir;
    std::cout << " (" << spec.ref << ")\n";

    // Download ZIP from GitHub
    HttpClientResponse resp = fetch_archive(spec, verbose);
    if (!resp.error.empty()) {
        std::cerr << "Download error: " << resp.error << "\n";
        return 1;
    }
    if (resp.status != 200) {
        std::cerr << "GitHub " << resp.status << " returned — module not found: "
                  << spec.user << "/" << spec.repo << "\n";
        return 1;
    }

    std::cout << "  " << (resp.body.size() / 1024) << " KB downloaded\n";

    // Extract to ~/.look/modules/<mod_name>/ — temp dir next to it, then swap (paketle aynı).
    // Modüllerin kilit dosyası yok: özet kaydı/doğrulaması yalnız proje paketlerinde (look.lock).
    fs::path dest_dir;
    try { dest_dir = modules_dir() / mod_name; }
    catch (const std::exception& e) { std::cerr << "Error: " << e.what() << "\n"; return 1; }
    std::error_code ec;
    fs::create_directories(dest_dir.parent_path(), ec);
    fs::path tmp = temp_sibling(dest_dir, "new");

    std::vector<char> zip_data(resp.body.begin(), resp.body.end());
    std::vector<std::pair<std::string, std::string>> digests;
    if (!extract_zip(zip_data, tmp, verbose, spec.subdir, digests)) {
        fs::remove_all(tmp, ec);
        std::cerr << "ZIP extraction error; " << dest_dir.string() << " was not changed\n";
        return 1;
    }
    std::string swap_err;
    if (!swap_into_place(tmp, dest_dir, swap_err)) {
        std::cerr << "Error: " << swap_err << "; the previous installation was kept.\n";
        return 1;
    }

    std::cout << "  → " << dest_dir.string() << "\n";
    std::cout << "✓ " << mod_name << " module installed\n\n";
    std::cout << "Usage:\n";
    std::cout << "  use " << mod_name << "\n";

    return 0;
}

