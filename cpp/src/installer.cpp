// ── look.lock helpers ─────────────────────────────────────────────────────────

struct LockEntry {
    std::string ref;    // "main", "v1.2", commit sha
    std::string sha;    // resolved commit sha (or "" if unknown)
    std::string hash;   // içerik özeti "h1:<base64>" (eski kilitte yok → "")
};

// Satır biçimi:  "user/repo[/subdir]" = "ref@sha h1:<base64>"
// Özet, değerin SON boşluktan sonraki "h1:" parçasıdır; eski satırlarda (özetsiz) yoktur ve
// aynen eskisi gibi ayrışır. Ref'ler (git) boşluk içeremez → ayırıcı belirsiz değil.
static void split_lock_hash(std::string& val, std::string& hash) {
    auto sp = val.rfind(' ');
    if (sp == std::string::npos) return;
    std::string tail = val.substr(sp + 1);
    if (tail.rfind("h1:", 0) != 0) return;
    hash = tail;
    val.erase(sp);
    while (!val.empty() && val.back() == ' ') val.pop_back();
}

// Read look.lock → map{"user/repo" → LockEntry}
static std::map<std::string, LockEntry> read_lock(const fs::path& lock_path) {
    std::map<std::string, LockEntry> result;
    if (!fs::exists(lock_path)) return result;

    std::ifstream f(lock_path);
    std::string line;
    while (std::getline(f, line)) {
        if (line.empty() || line[0] == '#') continue;
        // format: "user/repo" = "ref@sha"  or  "user/repo" = "ref"
        auto eq = line.find('=');
        if (eq == std::string::npos) continue;
        std::string key = line.substr(0, eq);
        std::string val = line.substr(eq + 1);
        // strip whitespace and quotes
        auto strip = [](std::string& s) {
            while (!s.empty() && (s.front() == ' ' || s.front() == '"')) s.erase(s.begin());
            while (!s.empty() && (s.back()  == ' ' || s.back()  == '"')) s.pop_back();
        };
        strip(key); strip(val);

        LockEntry e;
        split_lock_hash(val, e.hash);
        auto at = val.find('@');
        if (at != std::string::npos) {
            e.ref = val.substr(0, at);
            e.sha = val.substr(at + 1);
        } else {
            e.ref = val;
        }
        result[key] = e;
    }
    return result;
}

// Write look.lock from map (sorted, deterministic)
static void write_lock(const fs::path& lock_path,
                        const std::map<std::string, LockEntry>& entries)
{
    std::ofstream f(lock_path);
    f << "# look.lock — generated by look install, do not edit manually\n";
    for (auto& [key, e] : entries) {
        f << '"' << key << '"' << " = \"" << e.ref;
        if (!e.sha.empty()) f << '@' << e.sha;
        if (!e.hash.empty()) f << ' ' << e.hash;
        f << "\"\n";
    }
}

// ── Content checksum (look.lock "h1:") ────────────────────────────────────────
//
// NEDEN ZIP baytları değil de İÇERİK: GitHub zipball'ı her istekte yeniden üretebilir (sıkıştırma
// ayarı / zaman damgası / kök klasör adı değişebilir; GitHub arşiv bayt kararlılığını garanti
// etmiyor, 2023'te git-archive değişikliği yüzünden dünya çapında checksum'lar kırıldı). Aynı
// commit'in ZIP özeti sahte uyuşmazlık verebilir. Bunun yerine Go'nun dirhash "h1" algoritması:
// her dosya için "sha256hex  yol\n" (yollar sıralı, '/' ayırıcılı, kurulum köküne göreli), sonra
// bu özet metninin SHA-256'sı, base64. Dosya sistemine değil ARŞİVDEN okunan baytlara uygulanır
// (Windows'ta büyük/küçük harf duyarsız disk aynı içeriğe farklı özet vermesin).
static std::string base64_std(const std::vector<uint8_t>& in) {
    static const char* T = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    size_t i = 0;
    for (; i + 2 < in.size(); i += 3) {
        uint32_t v = (uint32_t(in[i]) << 16) | (uint32_t(in[i + 1]) << 8) | in[i + 2];
        out += T[(v >> 18) & 63]; out += T[(v >> 12) & 63]; out += T[(v >> 6) & 63]; out += T[v & 63];
    }
    if (i + 1 == in.size()) {
        uint32_t v = uint32_t(in[i]) << 16;
        out += T[(v >> 18) & 63]; out += T[(v >> 12) & 63]; out += "==";
    } else if (i + 2 == in.size()) {
        uint32_t v = (uint32_t(in[i]) << 16) | (uint32_t(in[i + 1]) << 8);
        out += T[(v >> 18) & 63]; out += T[(v >> 12) & 63]; out += T[(v >> 6) & 63]; out += '=';
    }
    return out;
}

static std::string hex_lower(const std::vector<uint8_t>& in) {
    static const char* H = "0123456789abcdef";
    std::string s;
    for (uint8_t b : in) { s += H[b >> 4]; s += H[b & 15]; }
    return s;
}

// files: (göreli yol, dosya sha256 hex) — sıralanır, yani arşiv içi sıra özeti etkilemez.
static std::string content_hash_h1(std::vector<std::pair<std::string, std::string>> files) {
    std::sort(files.begin(), files.end());
    std::string summary;
    for (auto& [name, h] : files) summary += h + "  " + name + "\n";
    return "h1:" + base64_std(sha256(std::vector<uint8_t>(summary.begin(), summary.end())));
}

// ── Atomic replace (temp dir next to the target, then rename) ─────────────────
//
// Eskiden önce eski paket remove_all ile siliniyor, sonra yeni açılıyordu: indirme sonrası her
// hata (bozuk ZIP, disk dolu, özet uyuşmazlığı) projeyi paketsiz bırakıyordu. Şimdi: hedefin
// YANINDA (aynı dosya sistemi → rename atomik) geçici dizine aç, doğrula, sonra yer değiştir.
static fs::path temp_sibling(const fs::path& dest, const char* tag) {
    static std::mt19937_64 rng(std::random_device{}() ^
        (uint64_t)std::chrono::steady_clock::now().time_since_epoch().count());
    std::string name = "." + dest.filename().string() + ".look-" + tag + "-" +
                       std::to_string(rng() % 100000000ull);
    return dest.parent_path() / name;
}

// tmp → dest. Başarısızlıkta eski paket yerinde kalır ve tmp silinir.
static bool swap_into_place(const fs::path& tmp, const fs::path& dest, std::string& err) {
    std::error_code ec;
    fs::path backup;
    if (fs::exists(dest, ec) || fs::is_symlink(dest, ec)) {
        backup = temp_sibling(dest, "old");
        fs::rename(dest, backup, ec);
        if (ec) {
            err = "could not move the old " + dest.string() + " aside: " + ec.message();
            fs::remove_all(tmp, ec);
            return false;
        }
    }
    fs::rename(tmp, dest, ec);
    if (ec) {
        err = "could not move the new files into " + dest.string() + ": " + ec.message();
        std::error_code ec2;
        if (!backup.empty()) fs::rename(backup, dest, ec2);
        fs::remove_all(tmp, ec2);
        return false;
    }
    if (!backup.empty()) {
        fs::remove_all(backup, ec);
        if (ec) std::cerr << "  warning: could not remove " << backup.string()
                          << ": " << ec.message() << "\n";
    }
    return true;
}

// ── Package name parsing ──────────────────────────────────────────────────────

struct PkgSpec {
    std::string host;    // "github.com"
    std::string user;
    std::string repo;
    std::string subdir;  // optional: "firebase" from look-packages/firebase
    std::string ref;     // branch/tag, default "main"

    // look.lock key: "user/repo" or "user/repo/subdir"
    std::string lock_key() const {
        return subdir.empty() ? (user + "/" + repo)
                              : (user + "/" + repo + "/" + subdir);
    }
    // local install dir: "pkg/firebase" (subdir name) or "pkg/user/repo"
    std::string pkg_dir() const {
        return subdir.empty() ? ("pkg/" + user + "/" + repo)
                              : ("pkg/" + subdir);
    }
    std::string zip_url() const {
        return "https://api.github.com/repos/" + user + "/" + repo + "/zipball/" + ref;
    }
};

static PkgSpec parse_pkg(const std::string& input) {
    PkgSpec p;
    std::string s = input;

    // strip leading https:// or http://
    if (s.substr(0, 8) == "https://") s = s.substr(8);
    else if (s.substr(0, 7) == "http://") s = s.substr(7);

    // optional @ref suffix
    auto at = s.rfind('@');
    if (at != std::string::npos) {
        p.ref = s.substr(at + 1);
        s     = s.substr(0, at);
    } else {
        p.ref = "main";
    }

    // host
    auto s1 = s.find('/');
    if (s1 == std::string::npos) throw std::runtime_error("Invalid package: " + input);
    p.host = s.substr(0, s1);
    s      = s.substr(s1 + 1);

    // user
    auto s2 = s.find('/');
    if (s2 == std::string::npos) throw std::runtime_error("Invalid package (user/repo required): " + input);
    p.user = s.substr(0, s2);
    s      = s.substr(s2 + 1);

    // repo[/subdir]
    auto s3 = s.find('/');
    if (s3 == std::string::npos) {
        p.repo = s;  // whole repo, no subdir
    } else {
        p.repo   = s.substr(0, s3);
        p.subdir = s.substr(s3 + 1);
        // strip trailing slash if any
        if (!p.subdir.empty() && p.subdir.back() == '/')
            p.subdir.pop_back();
    }

    if (p.host != "github.com")
        throw std::runtime_error("Only github.com is supported at the moment.");

    // Path-traversal koruması: user/repo/subdir doğrudan yerel hedef yola akıyor
    // (pkg_dir()="pkg/"+subdir, modules_dir()/mod_name). Kötü niyetli look.lock (klonlanmış
    // güvenilmeyen proje) veya CLI arg'ında `../` → dest_dir proje/modül kökünün DIŞINA
    // kaçar; extract_zip'in Zip-Slip kontrolü kaçmış dest_dir'i güvenli-taban sayar →
    // proje-dışına attacker-içerikli dosya yazımı. Her bileşeni katı doğrula.
    auto validate_component = [&input](const std::string& c, const char* what) {
        if (c.empty())
            throw std::runtime_error(std::string("Invalid package (empty ") + what + "): " + input);
        if (c == "." || c == ".." || c.find("..") != std::string::npos ||
            c.find('/') != std::string::npos || c.find('\\') != std::string::npos ||
            c.find(':') != std::string::npos || c.front() == '.' ||
            c.find('\0') != std::string::npos)
            throw std::runtime_error(std::string("Invalid package ") + what +
                                     " (path-escape character): " + input);
    };
    validate_component(p.user, "user");
    validate_component(p.repo, "repo");
    // subdir çok-seviyeli olabilir (a/b) — her segmenti ayrı doğrula
    if (!p.subdir.empty()) {
        size_t seg = 0, nx;
        do {
            nx = p.subdir.find('/', seg);
            std::string part = p.subdir.substr(seg, nx == std::string::npos ? nx : nx - seg);
            validate_component(part, "subdir");
            seg = nx + 1;
        } while (nx != std::string::npos);
    }

    return p;
}

// ── ZIP extraction ────────────────────────────────────────────────────────────

// GitHub zipball: "{repo}-{sha}/" prefix + optional subdir filter
// subdir_filter: if non-empty, only extract files under that subdirectory
static bool extract_zip(const std::vector<char>& data,
                         const fs::path& dest_dir,
                         bool verbose,
                         const std::string& subdir_filter,
                         std::vector<std::pair<std::string, std::string>>& digests)
{
    mz_zip_archive zip{};
    if (!mz_zip_reader_init_mem(&zip, data.data(), data.size(), 0)) {
        std::cerr << "ZIP open error: " << mz_zip_get_error_string(mz_zip_get_last_error(&zip)) << "\n";
        return false;
    }

    int n = (int)mz_zip_reader_get_num_files(&zip);
    if (n == 0) { mz_zip_reader_end(&zip); return false; }

    // GitHub prepends "repo-sha/" to all paths — detect and strip that prefix
    std::string strip_prefix;
    {
        mz_zip_archive_file_stat st;
        if (mz_zip_reader_file_stat(&zip, 0, &st)) {
            std::string first = st.m_filename;
            auto slash = first.find('/');
            if (slash != std::string::npos) strip_prefix = first.substr(0, slash + 1);
        }
    }

    // subdir filter prefix: after stripping GitHub prefix, files must start with "subdir/"
    std::string subdir_prefix = subdir_filter.empty() ? "" : (subdir_filter + "/");

    // ZIP bombası sınırı: açılmış toplam boyut (merkez dizindeki bildirilen boyutlar — miniz açarken
    // gerçek boyutu ve CRC'yi bildirilene karşı doğrular). Eskiden sınır yoktu: birkaç KB'lık arşiv
    // bellekte ve diskte GB'larca yer açtırabiliyordu. Karar saf dikişte (look/zip_safe.h).
    {
        std::vector<uint64_t> sizes;
        // girdi sayısı önce: zip64 milyarlarca girdi bildirebilir — vektörü onlarla doldurma
        int upto = n > (int)look::ZIP_MAX_ENTRIES ? (int)look::ZIP_MAX_ENTRIES + 1 : n;
        for (int i = 0; i < upto; ++i) {
            mz_zip_archive_file_stat st;
            sizes.push_back(mz_zip_reader_file_stat(&zip, i, &st) ? st.m_uncomp_size : 0);
        }
        std::string why = look::zip_size_problem(sizes);
        if (!why.empty()) {
            std::cerr << "Error: " << why << "; not installed.\n";
            mz_zip_reader_end(&zip); return false;
        }
    }

    fs::create_directories(dest_dir);
    int extracted = 0;

    for (int i = 0; i < n; ++i) {
        mz_zip_archive_file_stat st;
        if (!mz_zip_reader_file_stat(&zip, i, &st)) continue;

        std::string filename = st.m_filename;

        // Strip GitHub prefix
        if (!strip_prefix.empty() && filename.substr(0, strip_prefix.size()) == strip_prefix)
            filename = filename.substr(strip_prefix.size());
        if (filename.empty()) continue;

        // Subdir filter: skip files not under the requested subdirectory
        if (!subdir_prefix.empty()) {
            if (filename.substr(0, subdir_prefix.size()) != subdir_prefix) continue;
            // Strip subdir prefix so files land directly in dest_dir
            filename = filename.substr(subdir_prefix.size());
            if (filename.empty()) continue;
        }

        // Zip Slip koruması → saf dikişe taşındı (look/zip_safe.h; installer_zipslip_test
        // ağsız tablo-test eder, sibling-prefix kaçışı dahil pozitif-kontrollü).
        fs::path out_path = fs::weakly_canonical(dest_dir / filename);
        if (!look::zip_entry_inside_dest(filename, dest_dir)) {
            if (verbose) std::cerr << "  SKIPPED (security): " << filename << "\n";
            continue;
        }

        if (mz_zip_reader_is_file_a_directory(&zip, i)) {
            fs::create_directories(out_path);
            continue;
        }

        fs::create_directories(out_path.parent_path());

        // Açılamayan girdi (CRC/boyut uyuşmazlığı = bozuk/tahrif edilmiş arşiv) veya yazılamayan
        // dosya artık KURULUMU durdurur — eskiden atlanıyordu ve eksik paket "kuruldu" sayılıyordu.
        size_t out_size = 0;
        void* buf = mz_zip_reader_extract_to_heap(&zip, i, &out_size, 0);
        if (!buf) {
            std::cerr << "Error: could not extract " << filename << " ("
                      << mz_zip_get_error_string(mz_zip_get_last_error(&zip)) << ")\n";
            mz_zip_reader_end(&zip);
            return false;
        }

        const uint8_t* bytes = (const uint8_t*)buf;
        digests.emplace_back(filename,
            hex_lower(sha256(std::vector<uint8_t>(bytes, bytes + out_size))));
        std::ofstream ofs(out_path, std::ios::binary);
        if (ofs) ofs.write((const char*)buf, (std::streamsize)out_size);
        mz_free(buf);
        if (!ofs) {
            std::cerr << "Error: could not write " << out_path.string() << "\n";
            mz_zip_reader_end(&zip);
            return false;
        }
        ofs.close();
        ++extracted;

        if (verbose) std::cout << "  + " << filename << "\n";
    }

    mz_zip_reader_end(&zip);

    if (extracted == 0 && !subdir_filter.empty()) {
        std::cerr << "Error: '" << subdir_filter << "' folder not found in the repo.\n";
        return false;
    }
    return true;
}

// ── Download with redirect follow ─────────────────────────────────────────────

static HttpClientResponse download_follow(const std::string& url, bool verbose, int max_redirects = 5) {
    std::string current = url;
    HttpOptions opts;
    opts.timeout_ms = 30000;  // 30s for large ZIPs

    for (int i = 0; i < max_redirects; ++i) {
        if (verbose) std::cout << "  Downloading: " << current << "\n";

        std::map<std::string, std::string> headers;
        headers["Accept"]     = "application/zip";
        headers["User-Agent"] = "LOOK-Package-Manager/0.25";

        HttpClientResponse resp = http_request("GET", current, "", headers, opts);

        if (!resp.error.empty()) return resp;

        // 3xx redirect
        if (resp.status >= 300 && resp.status < 400) {
            auto it = resp.headers.find("location");
            if (it == resp.headers.end()) {
                resp.error = "redirect has no location header";
                return resp;
            }
            // Yönlendirme HEDEFİ doğrulanmalı — eskiden körlemesine takip ediliyordu.
            // İlk istek güvenli (zip_url() https sabit, parse_pkg host'u github.com'a
            // kısıtlı, TLS'te SSL_VERIFY_PEER + SSL_set1_host var). Ama yönlendirme
            // zinciri korumasızdı:
            //   * `Location: http://…`  → ŞEMA DÜŞÜRME: sonraki istek düz metin,
            //     yani TLS'in sağladığı bütünlük garantisi kaybolur (MITM penceresi).
            //   * `Location: https://baska-host/…` → tamamen farklı bir kaynaktan
            //     indirme.
            // Paket = ÇALIŞTIRILABİLİR LOOK KODU olduğu için bu bir tedarik zinciri
            // riski; savunma katmanı ucuz, bedeli ağır (asimetri).
            std::string next = it->second;
            // Redirect güvenlik-kararı → saf dikişe taşındı (look/url_safe.h; installer_redirect_test
            // ağsız tablo-test eder, şema-düşürme + host-kaçışı pozitif-kontrollü).
            if (!look::redirect_allowed(next, resp.error)) return resp;
            current = next;
            continue;
        }
        return resp;
    }

    HttpClientResponse r;
    r.error = "too many redirects";
    return r;
}

// Ağsız test dikişi: LOOK_INSTALL_ARCHIVE_DIR ayarlıysa arşiv GitHub yerine
// <dir>/<user>/<repo>/<ref>.zip dosyasından okunur. Commit sha'sı GitHub'ın
// Content-Disposition başlığı gibi taklit edilir: <ref>.sha dosyası varsa o, ref 40 hex ise ref.
// (tests/installer_integrity_test.sh). Kullanıcı ortamı zaten güvenilir; yine de her
// kullanımda stderr'e yazılır — sessiz kaynak değişimi olmasın.
static const char* archive_dir_override() {
    const char* d = std::getenv("LOOK_INSTALL_ARCHIVE_DIR");
    return (d && *d) ? d : nullptr;
}

static HttpClientResponse fetch_archive(const PkgSpec& spec, bool verbose) {
    const char* dir = archive_dir_override();
    if (!dir) return download_follow(spec.zip_url(), verbose);

    std::cerr << "  NOTE: LOOK_INSTALL_ARCHIVE_DIR is set; reading the archive from "
              << dir << ", not from GitHub\n";
    HttpClientResponse r;
    fs::path base = fs::path(dir) / spec.user / spec.repo;
    std::ifstream zf(base / (spec.ref + ".zip"), std::ios::binary);
    if (!zf) { r.status = 404; return r; }
    r.body.assign(std::istreambuf_iterator<char>(zf), std::istreambuf_iterator<char>());
    r.status = 200;
    std::string sha;
    std::ifstream sf(base / (spec.ref + ".sha"));
    if (sf) std::getline(sf, sha);
    else if (spec.ref.size() == 40) sha = spec.ref;
    while (!sha.empty() && (sha.back() == '\r' || sha.back() == ' ')) sha.pop_back();
    if (!sha.empty())
        r.headers["content-disposition"] =
            "attachment; filename=" + spec.user + "-" + spec.repo + "-" + sha + ".zip";
    return r;
}

// ── Resolve commit SHA via GitHub API ─────────────────────────────────────────

static std::string resolve_sha(const PkgSpec& spec, bool verbose) {
    // GET https://api.github.com/repos/{user}/{repo}/commits/{ref}
    std::string url = "https://api.github.com/repos/" + spec.user + "/" + spec.repo
                    + "/commits/" + spec.ref;
    if (archive_dir_override()) return "";   // test dikişi: ağa çıkma
    if (verbose) std::cout << "  resolving SHA...\n";

    std::map<std::string, std::string> hdrs;
    hdrs["Accept"]     = "application/vnd.github.sha";
    hdrs["User-Agent"] = "LOOK-Package-Manager/0.25";

    HttpOptions opts;
    opts.timeout_ms = 10000;
    HttpClientResponse resp = http_request("GET", url, "", hdrs, opts);
    if (!resp.error.empty() || resp.status != 200) return "";

    // Response body is just the 40-char SHA when Accept: application/vnd.github.sha
    std::string sha = resp.body;
    // trim whitespace
    while (!sha.empty() && (sha.back() == '\n' || sha.back() == '\r' || sha.back() == ' '))
        sha.pop_back();
    if (sha.size() == 40) return sha;
    return "";
}

// ── cmd_install ───────────────────────────────────────────────────────────────

int cmd_install(const std::string& pkg, bool verbose, bool locked) {
    PkgSpec spec;
    try {
        spec = parse_pkg(pkg);
    } catch (const std::exception& e) {
        std::cerr << "Error: " << e.what() << "\n";
        return 1;
    }

    // look.lock'u ÖNCE oku: --locked için kayıtlı sha'ya sabitle, ve normal kurulumda
    // ref'in kilitten bu yana kayıp kaymadığını (etiket taşındı / dal ilerledi) göster.
    auto lock_path = fs::current_path() / "look.lock";
    auto lock      = read_lock(lock_path);
    auto lock_it   = lock.find(spec.lock_key());
    std::string locked_sha = (lock_it != lock.end()) ? lock_it->second.sha : "";

    if (locked) {
        // Reprodüksiyon + tahrif-kanıtı: kayıtlı commit sha'sını AYNEN indir. Ref
        // (dal/etiket) o sha'dan başka bir şeye çözülse bile sha sabittir → GitHub
        // o sha için tam olarak o ağacı verir, sessiz ikame imkansız.
        if (locked_sha.empty()) {
            std::cerr << "Error: no locked version for " << spec.lock_key()
                      << " in look.lock — run 'look install " << pkg << "' first.\n";
            return 1;
        }
        spec.ref = locked_sha;
        if (verbose) std::cout << "  --locked: pinning to " << locked_sha << "\n";
    }

    std::cout << "Loading: " << spec.user << "/" << spec.repo;
    if (!spec.subdir.empty()) std::cout << "/" << spec.subdir;
    std::cout << " (" << spec.ref << ")\n";

    // Download ZIP
    HttpClientResponse resp = fetch_archive(spec, verbose);
    if (!resp.error.empty()) {
        std::cerr << "Download error: " << resp.error << "\n";
        return 1;
    }
    if (resp.status != 200) {
        std::cerr << "GitHub " << resp.status << " returned — package not found: "
                  << spec.user << "/" << spec.repo << "\n";
        return 1;
    }

    std::cout << "  " << (resp.body.size() / 1024) << " KB downloaded\n";

    // look.lock zaten yukarıda okundu (lock_path/lock/locked_sha).
    // Commit sha'sı ÇIKARMADAN ÖNCE belirlenir: özet doğrulaması ve --locked sha kontrolü
    // eski paket yerinden oynamadan yapılmalı.
    // Try to extract commit SHA from Content-Disposition or URL
    // GitHub sends: attachment; filename=user-repo-{sha}.zip
    std::string sha;
    auto it = resp.headers.find("content-disposition");
    if (it != resp.headers.end()) {
        auto& cd = it->second;
        auto fn_pos = cd.find("filename=");
        if (fn_pos != std::string::npos) {
            std::string fn = cd.substr(fn_pos + 9);
            // strip quotes
            if (!fn.empty() && fn[0] == '"') fn = fn.substr(1);
            auto q = fn.find('"');
            if (q != std::string::npos) fn = fn.substr(0, q);
            // filename = repo-sha.zip → extract sha
            auto dot = fn.rfind(".zip");
            if (dot != std::string::npos) fn = fn.substr(0, dot);
            auto dash = fn.rfind('-');
            if (dash != std::string::npos) {
                sha = fn.substr(dash + 1);
                // GitHub SHAs are 40 hex chars
                if (sha.size() != 40) sha.clear();
            }
        }
    }

    // Try to resolve exact commit SHA if not already extracted from zip filename
    if (sha.empty()) sha = resolve_sha(spec, verbose);

    // Kilitli kurulum: içeriğin gerçekten kilitli sha olduğunu doğrula (GitHub sha URL'i
    // için bunu garanti eder; yine de tahrif-kanıtı olarak kontrol et). Eski paket henüz yerinde.
    if (locked && !sha.empty() && !locked_sha.empty() && sha != locked_sha) {
        std::cerr << "Error: locked install integrity check failed for "
                  << spec.lock_key() << " — expected " << locked_sha
                  << " got " << sha << "\n";
        return 1;
    }

    // Extract into a temp dir next to the target; the old package stays until the swap.
    fs::path dest = spec.pkg_dir();
    std::error_code ec;
    fs::create_directories(dest.parent_path(), ec);
    fs::path tmp = temp_sibling(dest, "new");

    std::vector<char> zip_data(resp.body.begin(), resp.body.end());
    std::vector<std::pair<std::string, std::string>> digests;
    if (!extract_zip(zip_data, tmp, verbose, spec.subdir, digests)) {
        fs::remove_all(tmp, ec);
        std::cerr << "ZIP extraction error; " << dest.string() << " was not changed\n";
        return 1;
    }
    const std::string hash = content_hash_h1(digests);

    // go.sum gibi: look.lock bu commit için bir içerik özeti kaydetmişse indirilen içerik ONA
    // eşit olmalı. Aynı commit = kilitteki sha (sha bilinmiyorsa: ref'in kendisi kilitteki sha).
    const std::string locked_hash = (lock_it != lock.end()) ? lock_it->second.hash : "";
    const bool same_commit = !locked_sha.empty() &&
                             (sha == locked_sha || (sha.empty() && spec.ref == locked_sha));
    if (same_commit && sha.empty()) sha = locked_sha;
    if (same_commit && !locked_hash.empty() && hash != locked_hash) {
        fs::remove_all(tmp, ec);
        std::cerr << "Error: checksum mismatch for " << spec.lock_key()
                  << " at commit " << locked_sha << "\n"
                  << "  look.lock:  " << locked_hash << "\n"
                  << "  downloaded: " << hash << "\n"
                  << "The downloaded content is not what look.lock recorded; nothing was installed"
                  << " and " << dest.string() << " was not changed.\n";
        return 1;
    }

    std::string swap_err;
    if (!swap_into_place(tmp, dest, swap_err)) {
        std::cerr << "Error: " << swap_err << "; the previous installation was kept.\n";
        return 1;
    }
    std::cout << "  → " << dest.string() << "\n";
    if (same_commit && !locked_hash.empty())
        std::cout << "  checksum verified (" << hash << ")\n";

    if (locked) {
        // --locked look.lock'un ref/sha'sını DEĞİŞTİRMEZ. Tek istisna: eski kilitte özet yoksa
        // ilk görülen içerik kaydedilir (trust on first use).
        if (locked_hash.empty()) {
            lock[spec.lock_key()].hash = hash;
            write_lock(lock_path, lock);
            std::cout << "  look.lock: recorded checksum " << hash << " for "
                      << spec.lock_key() << "\n";
        }
        std::cout << "  --locked: verified " << locked_sha << "\n";
    } else {
        // Sessiz-ikame görünürlüğü: kullanıcı bir dal/etiket kurdu ve o ref kilitten
        // bu yana FARKLI bir commit'e çözüldüyse (etiket taşındı / dal ilerledi) bunu
        // AÇIKÇA bildir — normal kurulum güncellemeyi amaçlar ama sessiz olmamalı.
        if (!locked_sha.empty() && !sha.empty() && sha != locked_sha) {
            std::cout << "  NOTE: '" << spec.ref << "' moved since look.lock: "
                      << locked_sha.substr(0, 10) << " -> " << sha.substr(0, 10)
                      << "  (updating; use --locked to pin to the recorded commit)\n";
        }
        LockEntry entry;
        // `lk install` (argümansız) kilitteki sha'yı kurar: kayıtlı ref'i (ör. "main") sha ile ezme.
        entry.ref = (lock_it != lock.end() && spec.ref == locked_sha && !lock_it->second.ref.empty())
                        ? lock_it->second.ref : spec.ref;
        entry.sha = sha;
        entry.hash = hash;
        lock[spec.lock_key()] = entry;
        write_lock(lock_path, lock);
        if (same_commit && locked_hash.empty())
            std::cout << "  look.lock: recorded checksum " << hash << " for "
                      << spec.lock_key() << "\n";
        std::cout << "  look.lock updated\n";
    }
    std::cout << "✓ " << spec.lock_key() << " installed\n\n";
    std::cout << "Usage:\n";
    if (!spec.subdir.empty()) {
        // pkg/firebase/firebase.lk
        std::cout << "  use \"" << spec.pkg_dir() << "/" << spec.subdir << ".lk\";\n";
    } else {
        std::cout << "  use \"" << spec.pkg_dir() << "/" << spec.repo << ".lk\";\n";
    }

    return 0;
}

// ── cmd_install_all ───────────────────────────────────────────────────────────

int cmd_install_all(bool verbose, bool locked) {
    auto lock_path = fs::current_path() / "look.lock";
    if (!fs::exists(lock_path)) {
        std::cout << "look.lock not found — no packages to install.\n";
        return 0;
    }

    auto lock = read_lock(lock_path);
    if (lock.empty()) {
        std::cout << "look.lock is empty — no packages to install.\n";
        return 0;
    }

    std::cout << lock.size() << " installing package...\n";
    int failed = 0;
    for (auto& [key, entry] : lock) {
        // Kilit dosyasının amacı YENİDEN-ÜRETİLEBİLİRLİK: kayıtlı commit sha'sına
        // sabitle. Eskiden entry.ref (dal/etiket) kullanılıyordu → `look install`
        // her koşumda ref'i yeniden çözüyordu; dal HEAD'i ilerlerse (veya etiket
        // yeniden basılırsa) look.lock'ta sha yazılı olmasına rağmen FARKLI kod
        // kurulurdu — yani kilit hiç kilitlemiyordu. sha yoksa (eski lock) ref'e düş.
        if (locked && entry.sha.empty()) {
            std::cerr << "  " << key << ": no locked sha in look.lock (--locked is strict)\n";
            ++failed; continue;
        }
        const std::string& pin = entry.sha.empty() ? entry.ref : entry.sha;
        std::string pkg_str = "github.com/" + key + "@" + pin;
        if (cmd_install(pkg_str, verbose, locked) != 0) ++failed;
    }

    if (failed > 0) {
        std::cerr << failed << " package could not be installed.\n";
        return 1;
    }
    std::cout << "All packages installed.\n";
    return 0;
}

